export type ModelId = 'llama3:latest' | 'gemini-2.5-flash' | 'qwen-2.5-coder';
export type ChainStep = { id: string; title: string; prompt: string; output: string };
export function interpolate(template: string, vars: Record<string, string>) {
  return template.replace(/{{\s*(\w+)\s*}}/g, (_, key: string) => vars[key] ?? `{{${key}}}`);
}
export function simulateResponse(prompt: string, model: ModelId) {
  const start = performance.now();
  const excerpt = prompt.trim().slice(0, 180) || 'No prompt content provided';
  const output = model.includes('coder')
    ? `// Generated by ${model}\nexport interface Result {\n  summary: string;\n  confidence: number;\n}\n\n// Task context: ${excerpt.replace(/\n/g, ' ')}\nexport const result: Result = { summary: 'Structured response generated locally.', confidence: 0.94 };\n`
    : JSON.stringify({ model, result: `Local simulation for: ${excerpt}`, key_points: ['Prompt received', 'Template variables resolved', 'Connect a provider endpoint for live inference'], confidence: 0.94 }, null, 2);
  return { output, latency: Math.max(120, Math.round(performance.now() - start + 320)), tokens: Math.max(18, Math.ceil(prompt.length / 4) + Math.ceil(output.length / 4)) };
}
export function downloadText(filename: string, content: string, type = 'application/json') {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = document.createElement('a'); a.href = url; a.download = filename; a.click(); URL.revokeObjectURL(url);
}
